package i18n

import "testing"

// {0}, {1} — номера аргументов: перевод может переставить их, значения должны встать на свои места.
// Раньше подстановка шла по порядку, и «Завтраков {1}, например: {0}» выдавала список вместо числа.
func TestNumberedPlaceholders(t *testing.T) {
	if got := T(RU, "cook.faq.breakfast.a", "омлет", 12); got != "Завтраков 12, например: омлет." {
		t.Fatalf("переставленные номера: %q", got)
	}
	if got := T(RU, "age.months", 8); got != "8 мес" {
		t.Fatalf("именованная подстановка по порядку: %q", got)
	}
}
